const fs=require("fs"),path=require("path"),assert=require("assert/strict");
const root=path.resolve(__dirname,"..");
const register=fs.readFileSync(path.join(root,"register.html"),"utf8");
const verify=fs.readFileSync(path.join(root,"verify.html"),"utf8");
const css=fs.readFileSync(path.join(root,"verify.css"),"utf8");
const guard=fs.readFileSync(path.join(root,"guard.html"),"utf8");
assert(register.includes('id="rememberTrustedDevice"'),"registration must expose explicit save-phone option");
assert(!/id="rememberTrustedDevice"[^>]*required/.test(register),"save-phone option must remain optional");
assert(register.includes("rememberDevice ? getTrustedDeviceId()"),"registration must bind device only when save-phone is selected");
assert(register.includes("rememberDevice ? pendingDeviceToken : null"),"registration must submit no device token when save-phone is off");
assert(verify.includes('<script src="./access-control.js"></script>'),"verify page must be directly reachable for QR scanning");
assert(!verify.includes('data-roles="EMPLOYEE"'),"verify page must not require portal employee session");
assert(verify.includes('id="manualSections" class="hidden"'),"manual verification must be hidden by default");
assert(verify.includes("webkit-playsinline"),"mobile camera video must request inline playback");
assert(css.includes("width:min(360px,100%)")&&css.includes("height:240px"),"camera preview must stay constrained inside the page");
assert(guard.includes("#result{position:fixed;inset:0;z-index:9999"),"guard result must cover the full viewport");
assert(guard.includes("resultUntil=Date.now()+10000"),"guard fullscreen result must remain timed for 10 seconds");
assert(guard.includes("el('qrPanel').hidden=true"),"QR panel must be hidden while result is shown");
console.log("PASS saved-phone QR flow is direct, camera is inline, and guard result is timed fullscreen");
